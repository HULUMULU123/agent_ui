def resolve_operation_type(subject_id: str, action_id: str | None, flags: list[str], direction: str) -> str:
    if subject_id == "loan" and action_id == "provision" and direction == "outflow" and "interest_free" in flags:
        return "Предоставление беспроцентного займа"
    return (OPERATION_TYPE_BY_ACTION.get((subject_id, action_id, direction))
            or OPERATION_TYPE_BY_SUBJECT.get(subject_id, "Неопознанный платёж"))

