def resolve_documents(operation_type: str, action_id: str | None, flags: list[str], direction: str) -> list[str]:
    docs = list(OPERATION_MATRIX.get(operation_type, OPERATION_MATRIX["Неопознанный платёж"])["requested_documents"])
    for extra in ACTION_DOCS.get(action_id, []) + [d for f in flags for d in FLAG_DOCS.get(f, [])]:
        if extra not in docs:
            docs.append(extra)
    if direction == "outflow" and operation_type not in UNKNOWN_TYPES and OUTFLOW_OVERLAY_DOC not in docs:
        docs.append(OUTFLOW_OVERLAY_DOC)
    return docs

